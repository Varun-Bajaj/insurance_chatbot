def create_jwt_token(user_info: User, client_id):
    """
    :param user_info:
    :return:
    """
    _dict = {
        "client_id": str(client_id),
        "user_id": str(user_info.user_id),
        "exp": datetime.utcnow() + timedelta(minutes=ACCESS_TOKEN_EXPIRE_MINUTES)
    }

    jwt_token = jwt.encode(claims=_dict, key=JWT_TOKEN_KEY , algorithm=ALGORITHM)
    return jwt_token


