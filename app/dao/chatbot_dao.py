def add_modeldetails(vid, name, datasets, approach, inuse, db):
    detail_data = db.query(Details).filter(Details.inuse == True).first()
    if detail_data is not None and inuse:
        if detail_data.name != vid or detail_data.name != name:
            detail_data.inuse = False
            db.add(detail_data)
            db.commit()

    data = Details(vid=vid, name=name, datasets=datasets, approach=approach, inuse=inuse)
    db.add(data)
    db.commit()
    return "Data inserted"


